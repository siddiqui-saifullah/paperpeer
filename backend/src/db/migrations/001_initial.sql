-- Tenant isolation: every table carries school_id, and references between tenant
-- tables are composite (school_id, id) foreign keys. A row in one school therefore
-- cannot point at a row in another, even if a query has a bug.

CREATE TABLE schools (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  code TEXT NOT NULL UNIQUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE classes (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  school_id INTEGER NOT NULL REFERENCES schools(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  UNIQUE (school_id, name),
  UNIQUE (school_id, id)
);
CREATE UNIQUE INDEX classes_name ON classes (school_id, lower(name));

CREATE TABLE users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  school_id INTEGER NOT NULL REFERENCES schools(id) ON DELETE CASCADE,
  role TEXT NOT NULL CHECK (role IN ('admin', 'teacher', 'student')),
  name TEXT NOT NULL,
  username TEXT NOT NULL,
  password_hash TEXT NOT NULL,
  must_change_password INTEGER NOT NULL DEFAULT 0,
  class_id INTEGER,
  roll_no TEXT,
  active INTEGER NOT NULL DEFAULT 1,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (school_id, username),
  UNIQUE (school_id, id),
  FOREIGN KEY (school_id, class_id) REFERENCES classes (school_id, id)
);
CREATE INDEX users_class ON users (school_id, class_id);

CREATE TABLE sessions (
  token_hash TEXT PRIMARY KEY,
  school_id INTEGER NOT NULL,
  user_id INTEGER NOT NULL,
  expires_at BIGINT NOT NULL,
  FOREIGN KEY (school_id, user_id) REFERENCES users (school_id, id) ON DELETE CASCADE
);

CREATE TABLE exams (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  school_id INTEGER NOT NULL,
  class_id INTEGER NOT NULL,
  title TEXT NOT NULL,
  subject TEXT NOT NULL,
  exam_date TEXT,
  max_marks DOUBLE PRECISION NOT NULL CHECK (max_marks > 0),
  status TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'collecting', 'review')),
  peer_sharing INTEGER NOT NULL DEFAULT 1,
  anonymous INTEGER NOT NULL DEFAULT 1,
  marks_released INTEGER NOT NULL DEFAULT 0,
  created_by INTEGER NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (school_id, id),
  FOREIGN KEY (school_id, class_id) REFERENCES classes (school_id, id),
  FOREIGN KEY (school_id, created_by) REFERENCES users (school_id, id)
);
CREATE INDEX exams_school ON exams (school_id, class_id);

CREATE TABLE submissions (
  id TEXT PRIMARY KEY,
  school_id INTEGER NOT NULL,
  exam_id INTEGER NOT NULL,
  student_id INTEGER NOT NULL,
  marks DOUBLE PRECISION,
  feedback TEXT NOT NULL DEFAULT '',
  is_model INTEGER NOT NULL DEFAULT 0,
  hidden_from_peers INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (exam_id, student_id),
  UNIQUE (school_id, id),
  FOREIGN KEY (school_id, exam_id) REFERENCES exams (school_id, id) ON DELETE CASCADE,
  FOREIGN KEY (school_id, student_id) REFERENCES users (school_id, id)
);

CREATE TABLE files (
  id TEXT PRIMARY KEY,
  school_id INTEGER NOT NULL,
  exam_id INTEGER NOT NULL,
  submission_id TEXT,
  kind TEXT NOT NULL CHECK (kind IN ('paper', 'solution', 'answer')),
  stored_name TEXT NOT NULL,
  original_name TEXT NOT NULL,
  mime TEXT NOT NULL,
  size INTEGER NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  FOREIGN KEY (school_id, exam_id) REFERENCES exams (school_id, id) ON DELETE CASCADE,
  FOREIGN KEY (school_id, submission_id) REFERENCES submissions (school_id, id) ON DELETE CASCADE
);
CREATE INDEX files_exam ON files (exam_id);
CREATE INDEX files_submission ON files (submission_id);

CREATE TABLE helpful_marks (
  school_id INTEGER NOT NULL,
  submission_id TEXT NOT NULL,
  student_id INTEGER NOT NULL,
  PRIMARY KEY (submission_id, student_id),
  FOREIGN KEY (school_id, submission_id) REFERENCES submissions (school_id, id) ON DELETE CASCADE,
  FOREIGN KEY (school_id, student_id) REFERENCES users (school_id, id)
);

CREATE TABLE notes (
  school_id INTEGER NOT NULL,
  exam_id INTEGER NOT NULL,
  student_id INTEGER NOT NULL,
  body TEXT NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (exam_id, student_id),
  FOREIGN KEY (school_id, exam_id) REFERENCES exams (school_id, id) ON DELETE CASCADE,
  FOREIGN KEY (school_id, student_id) REFERENCES users (school_id, id)
);
