-- Question-level scoring. An exam can be split into questions, each tagged with a
-- topic. Marking then records marks per question plus the kind of mistake made,
-- which feeds the Mistake Map, the student Skill Map and Peer Bridge.

CREATE TABLE questions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  school_id INTEGER NOT NULL,
  exam_id INTEGER NOT NULL,
  position INTEGER NOT NULL,
  label TEXT NOT NULL,
  topic TEXT NOT NULL DEFAULT '',
  max_marks DOUBLE PRECISION NOT NULL CHECK (max_marks > 0),
  UNIQUE (school_id, id),
  UNIQUE (exam_id, position),
  FOREIGN KEY (school_id, exam_id) REFERENCES exams (school_id, id) ON DELETE CASCADE
);
CREATE INDEX questions_exam ON questions (school_id, exam_id);

CREATE TABLE question_scores (
  school_id INTEGER NOT NULL,
  submission_id TEXT NOT NULL,
  question_id INTEGER NOT NULL,
  marks DOUBLE PRECISION NOT NULL CHECK (marks >= 0),
  mistake TEXT CHECK (mistake IN ('concept', 'calculation', 'misread', 'incomplete', 'unattempted')),
  PRIMARY KEY (submission_id, question_id),
  FOREIGN KEY (school_id, submission_id) REFERENCES submissions (school_id, id) ON DELETE CASCADE,
  FOREIGN KEY (school_id, question_id) REFERENCES questions (school_id, id) ON DELETE CASCADE
);
CREATE INDEX question_scores_question ON question_scores (school_id, question_id);
